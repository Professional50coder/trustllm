import { stringify } from 'yaml'
import type { Rule } from '@/lib/core/guardrails'

export interface ExportInput {
  mode: 'demo' | 'live'
  samples: number
  provider?: { kind: 'openai' | 'anthropic'; presetId?: string }
  models: string[]
  judgeModel?: string
  cases: { id?: string; prompt: string; context?: string; answer?: string }[]
  rules: Rule[]
}

/** Builds a trustllm.yaml for the CLI / GitHub Action from what the user just ran. Contains no keys. */
export function buildConfigYaml(i: ExportInput): string {
  const base = i.provider?.presetId && i.provider.presetId !== 'openai' ? { base_url: i.provider.presetId } : {}
  const doc: Record<string, unknown> = { mode: i.mode, samples: i.samples }
  if (i.mode === 'live' && i.provider) {
    doc.models = i.models.map((model) => ({ provider: i.provider!.kind, model, ...base }))
    if (i.judgeModel) doc.judge = { provider: i.provider.kind, model: i.judgeModel, ...base }
  } else if (i.mode === 'demo') {
    doc.models = i.models.map((model) => ({ provider: 'demo', model }))
  }
  doc.cases = i.cases
  doc.guardrails = i.rules
  return `# Generated by TrustLLM. API keys are read from OPENAI_API_KEY / ANTHROPIC_API_KEY at run time.\n# Run: node dist/cli.cjs run trustllm.yaml  (or use the GitHub Action)\n${stringify(doc)}`
}
